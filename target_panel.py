def build_program_row(cancer: str, targets: list[str], format_code: str, clinical_stage: str = "preclinical") -> dict[str, Any]:
    """Compose a DecisionMaking-compatible row dict for a target/modality combo.

    format_code should be one of DecisionMaking's _FORMAT_PATTERNS keys
    (e.g. "adc_cleavable", "adc_noncleavable", "bite_format", "masked_tce",
    "cobra_bispec", "dual_logic_car") so its regex-based detector recognises
    the format from raw_text.
    """
    format_keywords = {
        "adc_cleavable": "cleavable linker vedotin ADC",
        "adc_noncleavable": "non-cleavable DM4 ADC",
        "probody_dc": "Probody drug conjugate masked ADC protease-activated",
        "bite_format": "BiTE T-cell engager tandem scFv",
        "hle_bite": "half-life extended IgG-like T-cell engager",
        "masked_tce": "masked BiTE tumor-activated conditional T-cell engager",
        "cobra_bispec": "COBRA conditional bispecific protease-activated T-cell redirection",
        "dual_logic_car": "dual AND-gate tandem CAR-T",
    }
    raw_text = (
        f"{' x '.join(targets)} targeting program in {cancer.replace('_', ' ')} cancer, "
        f"{format_keywords.get(format_code, format_code)}"
    )
    return {
        "indication": "oncology",
        "mechanism": "antibody" if format_code not in ("dual_logic_car",) else "cell_therapy",
        "clinical_stage": clinical_stage,
        "raw_text": raw_text,
    }


def evaluate_dual_target_combos(cancer: str, db_path=None) -> list[dict[str, Any]]:
    """Run every dual-TAA combo for a cancer type through the real
    quantitative + qualitative decision pipeline in research_decision_bridge.py."""
    from research_decision_bridge import evaluate_research_program, DECISION_MAKING_ROOT

    if db_path is None:
        db_path = DECISION_MAKING_ROOT / "data" / "bioventure.json"

    results = []
    for combo in DUAL_TARGET_COMBOS.get(cancer, []):
        format_code = {
            "adc": "adc_cleavable",
            "tce": "cobra_bispec",
            "cart": "dual_logic_car",
        }[combo["modality"]]
        row = build_program_row(cancer, combo["targets"], format_code)
        report = evaluate_research_program(row, db_path=db_path)
        results.append({"combo": combo, "row": row, "report": report})
    return results


def print_single_target_panels() -> None:
    for cancer, modalities in CANCER_TARGET_PANELS.items():
        print(f"\n=== {cancer.upper()} ===")
        for modality, targets in modalities.items():
            print(f"  -- {modality.upper()} top {len(targets)} --")
            for t in targets:
                print(f"    {t['rank']:2d}. {t['target']:28s} [{t['stage']:20s}] {t['rationale']}")


def print_dual_target_combos(cancer: str | None = None, run_pipeline: bool = False) -> None:
    cancers = [cancer] if cancer else list(DUAL_TARGET_COMBOS.keys())
    for c in cancers:
        print(f"\n=== {c.upper()} dual-target (AND-gate) combos ===")
        if run_pipeline:
            for item in evaluate_dual_target_combos(c):
                combo, report = item["combo"], item["report"]
                q = report["quantitative"]
                print(f"  [{combo['modality'].upper()}] {' + '.join(combo['targets'])} ({combo['format']})")
                print(f"    rationale: {combo['rationale']}")
                print(f"    P(success)={q['p_success']:.1%}  verdict={q['verdict']}  final={report['final_recommendation']}")
        else:
            for combo in DUAL_TARGET_COMBOS[c]:
                print(f"  [{combo['modality'].upper()}] {' + '.join(combo['targets'])} ({combo['format']})")
                print(f"    rationale: {combo['rationale']}")


